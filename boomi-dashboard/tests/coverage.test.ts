test("every Companion plugin's scripts: recorded as steps, and gated only where they change something in Boomi", () => {
  const wrong: string[] = []
  for (const [script, sub, isStep, isGated] of COVERAGE) {
    const command = `bash /x/scripts/${script}${sub ? ` ${sub}` : ''} arg1`
    const step = scriptRuns(command).length > 0
    const gated = companionChanges(command).length > 0
    if (step !== isStep || gated !== isGated) wrong.push(`${script} ${sub}: step ${step} (want ${isStep}), gated ${gated} (want ${isGated})`)
  }
  expect(wrong).toEqual([])
  expect(COVERAGE.length).toBeGreaterThan(150)
})
